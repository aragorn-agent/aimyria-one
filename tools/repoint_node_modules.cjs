// Repoint pnpm's symlinks after the source tree moved.
//
// The tree was moved from the workspace (a non-ASCII path, which MinGW's
// windres cannot read) to D:\src. pnpm stores every package link as an absolute
// path into its own .pnpm store, so all ~1500 of them still point at the old
// location and every `pnpm run` resolves through a path that no longer holds
// the files we care about.
//
// Reinstalling would fix it too, but that needs the network. Rewriting the link
// targets is local, exact, and leaves the lockfile alone.
//
// Links are recreated as junctions: they need no elevation, and Windows
// resolves them faster than symlinks. The relative layout is identical because
// node_modules moved as one tree.
'use strict';
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const OLD = 'D:\\中转站运营\\_aimyria-one';
const NEW = 'D:\\src\\cc-switch-main';
const ROOT = path.join(NEW, 'node_modules');

if (!fs.existsSync(ROOT)) {
  console.error('node_modules not found at ' + ROOT);
  process.exit(1);
}

/** Every reparse point under `dir`. */
function findLinks(dir, out = []) {
  let entries;
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return out;
  }
  for (const e of entries) {
    const p = path.join(dir, e.name);
    let st;
    try {
      st = fs.lstatSync(p);
    } catch {
      continue;
    }
    if (e.isSymbolicLink()) {
      out.push(p);
      continue;
    }
    // Windows junctions report as directories in readdir but carry the
    // ReparsePoint attribute; reach them through lstat's stats.
    if (st.isDirectory()) {
      const isReparse = (st.mode & 0o170000) === 0o120000;
      if (isReparse) {
        out.push(p);
      } else {
        findLinks(p, out);
      }
    }
  }
  return out;
}

const links = findLinks(ROOT);
console.log('found ' + links.length + ' links');

let fixed = 0;
let skipped = 0;
const failures = [];

for (const link of links) {
  let target;
  try {
    target = fs.readlinkSync(link);
  } catch {
    skipped++;
    continue;
  }
  if (!target.toLowerCase().startsWith(OLD.toLowerCase())) continue;

  const rewritten = NEW + target.slice(OLD.length);

  try {
    fs.unlinkSync(link);
  } catch {
    // A directory junction cannot be unlink'd on Windows; rmdir removes the
    // reparse point only and never touches the target.
    try {
      execFileSync('cmd', ['/c', 'rmdir', link], { stdio: 'ignore' });
    } catch {
      failures.push(link + ': cannot remove');
      continue;
    }
  }

  try {
    execFileSync('cmd', ['/c', 'mklink', '/J', link, rewritten], { stdio: 'ignore' });
    fixed++;
  } catch (e) {
    failures.push(link + ': mklink failed (' + e.status + ')');
  }
}

console.log('repointed: ' + fixed);
console.log('skipped (not links): ' + skipped);
if (failures.length) {
  console.log('failures: ' + failures.length);
  for (const f of failures.slice(0, 10)) console.log('  ' + f);
}