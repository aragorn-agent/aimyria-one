// Brand and honesty checks that a code review can miss.
//
// These are the rules that are easy to state and easy to violate by accident:
// nobody adds a blue button on purpose, but a Tailwind default class, an
// upstream string that survived the strip, or a claim of original authorship
// all slip in the same way — quietly, in a diff nobody reads closely.
//
// Run from the repo root:
//   node tools/check_brand.mjs

